import type { Metadata } from 'next';
import { Container } from '@/components/ui/Container';
import { PredictionsPageHeader } from '@/components/predictions/PageHeader';
import { PredictionsGrid } from '@/components/predictions/PredictionsGrid';
import { fetchApi } from '@/lib/api/server';
import { Prediction } from '@/types/api';

export const metadata: Metadata = {
  title: "Today's Football Predictions",
  description: 'AI-generated football predictions for every match kicking off today.',
};

export default async function TodayPredictionsPage() {
  const { data } = await fetchApi<Prediction[]>('/predictions?when=today&limit=50', {
    revalidate: 120,
    tags: ['predictions', 'predictions-today'],
  });

  return (
    <>
      <PredictionsPageHeader
        eyebrow="Today"
        title="Today's Predictions"
        subtitle="Every free prediction for matches kicking off today, generated by our statistical model."
      />
      <Container className="py-10 sm:py-12">
        <PredictionsGrid
          predictions={data ?? []}
          emptyMessage="No predictions for today's fixtures yet — they're generated automatically as kickoff approaches."
        />
      </Container>
    </>
  );
}
